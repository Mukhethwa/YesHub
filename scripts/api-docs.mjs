#!/usr/bin/env node
/*
 * Builds docs/api/openapi.yaml, the OpenAPI 3 (Swagger) description of MASLink's API, and docs/api/index.html,
 * a Swagger UI page to read it in.
 *
 *   pnpm docs:api          from the Convex deployment in .env.local (your branch's code)
 *   pnpm docs:api --prod   from production
 *
 * The Convex functions come from `convex function-spec` through convex-helpers' OpenAPI generator, so their
 * arguments and return types are exactly what the code declares. This script then names the API, groups the
 * functions by area, describes each one from its doc comment, and adds the Next.js routes (sign-in and the
 * AI company summary) that run on the website rather than on Convex. Internal functions are left out: nothing
 * outside Convex can call them.
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parse, stringify } from "yaml";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const prod = process.argv.includes("--prod");
const out = path.join(root, "docs", "api");

const PRODUCTION = { convex: "posh-seahorse-411", site: "https://yeshub-app.vercel.app" };

/* ------------------------------------------------------------------------------------------------------ */
/* 1. Generate the raw spec                                                                               */
/* ------------------------------------------------------------------------------------------------------ */

const work = mkdtempSync(path.join(tmpdir(), "maslink-api-"));
const run = (command) => execSync(command, { cwd: root, stdio: ["ignore", "pipe", "inherit"], shell: true }).toString();

console.log(`Reading the function spec from ${prod ? "production" : "the deployment in .env.local"}…`);
const functionSpec = run(`pnpm exec convex function-spec${prod ? " --prod" : ""}`);
writeFileSync(path.join(work, "function-spec.json"), functionSpec);
run(
  `pnpm exec convex-helpers open-api-spec --input-file "${path.join(work, "function-spec.json")}" --output-file "${path.join(work, "convex")}"`,
);
const spec = parse(readFileSync(path.join(work, "convex.yaml"), "utf8"));
rmSync(work, { recursive: true, force: true });

/* ------------------------------------------------------------------------------------------------------ */
/* 2. Describe it                                                                                          */
/* ------------------------------------------------------------------------------------------------------ */

const { version } = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));

spec.info = {
  title: "MASLink API",
  version,
  description: [
    "MASLink matches South African SMEs with tenders, RFQs and enterprise and supplier development (ESD) programmes.",
    "",
    "**Convex functions.** Most of the API is Convex queries and mutations. The web app calls them over a live",
    "WebSocket; anything else can call the same functions over HTTP with `POST /api/run/{module}/{function}` and",
    'the arguments as `{ "args": { … } }`. Queries read, mutations write. A successful call returns',
    '`{ "status": "success", "value": … }`.',
    "",
    "**Signing in.** Accounts sign in through Better Auth on the website (`/api/auth/…`, below). For Convex calls,",
    "get a token from `GET /api/auth/convex/token` and send it as `Authorization: Bearer {token}`. Every function",
    "checks who is calling: SMEs only reach their own profile and applications, organisation members their own",
    "organisation's listings, and the admin functions MASLink staff with the right permission. Most functions",
    "return `null` rather than an error when the caller isn't allowed.",
    "",
    "**What SMEs see.** SMEs see only the status of their own applications (in progress, submitted, withdrawn, or",
    "accepted into an ESD programme), never their evaluation, ranking, buyer activity or a buyer's decision.",
    "",
    "Generated by `pnpm docs:api` from the code; don't edit openapi.yaml by hand.",
  ].join("\n"),
};

spec.servers = [
  {
    url: "https://{deployment}.convex.cloud",
    description: "Convex (functions)",
    variables: {
      deployment: {
        default: PRODUCTION.convex,
        description: "posh-seahorse-411 is production; use your development deployment's name for local testing",
      },
    },
  },
];

/** Each Convex module is a tag: the area of the product it serves. */
const AREAS = {
  account: "The signed-in account: whether it's an SME, a member of an organisation, or MASLink staff.",
  auth: "The signed-in user.",
  public: "Public figures for the website. No sign-in needed.",
  smes: "SME business profiles and their compliance documents. For the signed-in SME.",
  smeOpportunities:
    "The SME portal's opportunities: matches, support programmes, applying, unfinished applications and withdrawing. SMEs see only their own application status.",
  enterprise:
    "The corporate portal: listings and ESD programmes with their applicants, suppliers, shortlists, team and settings. For members of the caller's organisation.",
  opportunities:
    "Creating and running listings and ESD programmes: drafts, publishing, amending, closing and cancelling. For members of the organisation.",
  tenders: "Reading a tender document into its requirements register, and the buyer confirming it.",
  review: "Document review and automated shortlisting of applications, with the trail of every step.",
  enterpriseAudit: "An organisation's audit log: every change, who made it, and each field before and after.",
  admin: "MASLink staff: users, SMEs, organisations, listings and staff. Each checks the caller's staff permissions.",
  analytics: "Platform analytics for MASLink staff.",
  audit: "The platform-wide audit and change log, for MASLink staff.",
};
const ORDER = Object.keys(AREAS);

/** Doc comments above each `export const name =` in convex/<module>.ts, keyed by "module.name". */
function docComments(module) {
  const file = path.join(root, "convex", `${module}.ts`);
  if (!existsSync(file)) return {};
  const source = readFileSync(file, "utf8");
  const docs = {};
  for (const match of source.matchAll(/\/\*\*([\s\S]*?)\*\/\s*export const (\w+)\s*=/g)) {
    docs[match[2]] = match[1]
      .split("\n")
      .map((line) => line.replace(/^\s*\*\s?/, "").trimEnd())
      .join("\n")
      .trim();
  }
  return docs;
}

const docsByModule = {};
const seen = new Set();
for (const [route, item] of Object.entries(spec.paths)) {
  const match = /^\/api\/run\/(.+)\/([^/]+)$/.exec(route);
  if (!match) continue;
  const [, module, name] = match;
  docsByModule[module] ??= docComments(module);
  seen.add(module);
  for (const operation of Object.values(item)) {
    const kind = operation.tags?.[0] ?? "function";
    operation.tags = [module];
    operation.operationId = `${module}.${name}`;
    operation.summary = `${name} (${kind})`;
    operation["x-convex-function"] = `${module}:${name}`;
    operation["x-convex-type"] = kind;
    const doc = docsByModule[module][name];
    operation.description = doc ?? `Convex ${kind} \`${module}:${name}\`.`;
  }
}

spec.tags = [...seen]
  .sort((a, b) => (ORDER.includes(a) ? ORDER.indexOf(a) : 99) - (ORDER.includes(b) ? ORDER.indexOf(b) : 99))
  .map((name) => ({ name, description: AREAS[name] ?? `Convex functions in convex/${name}.ts.` }));

/* ------------------------------------------------------------------------------------------------------ */
/* 3. The website's own routes                                                                            */
/* ------------------------------------------------------------------------------------------------------ */

const site = [
  { url: PRODUCTION.site, description: "Website (Next.js)" },
  { url: "http://localhost:3000", description: "Local" },
];
const json = (schema) => ({ "application/json": { schema } });
const error = { description: "Something went wrong", content: json({ $ref: "#/components/schemas/RouteError" }) };
const authRoute = (operationId, summary, description, body, response) => ({
  tags: ["website"],
  operationId,
  summary,
  description,
  servers: site,
  security: [],
  ...(body ? { requestBody: { required: true, content: json(body) } } : {}),
  responses: { 200: { description: "OK", content: json(response) }, 400: error, 401: error },
});

Object.assign(spec.paths, {
  "/api/auth/sign-up/email": {
    post: authRoute(
      "auth.signUpEmail",
      "Create an account",
      "Better Auth. Creates an account with an email and password and signs it in (sets the session cookie).",
      {
        type: "object",
        required: ["name", "email", "password"],
        properties: {
          name: { type: "string" },
          email: { type: "string", format: "email" },
          password: { type: "string", minLength: 8 },
        },
      },
      { $ref: "#/components/schemas/Session" },
    ),
  },
  "/api/auth/sign-in/email": {
    post: authRoute(
      "auth.signInEmail",
      "Sign in",
      "Better Auth. Signs in with an email and password and sets the session cookie.",
      {
        type: "object",
        required: ["email", "password"],
        properties: {
          email: { type: "string", format: "email" },
          password: { type: "string" },
          rememberMe: { type: "boolean", default: true },
        },
      },
      { $ref: "#/components/schemas/Session" },
    ),
  },
  "/api/auth/sign-out": {
    post: authRoute("auth.signOut", "Sign out", "Better Auth. Ends the session in the cookie.", null, {
      type: "object",
      properties: { success: { type: "boolean" } },
    }),
  },
  "/api/auth/get-session": {
    get: {
      ...authRoute(
        "auth.getSession",
        "The current session",
        "Better Auth. The signed-in user and session, or null.",
        null,
        {
          $ref: "#/components/schemas/Session",
        },
      ),
      security: [{ sessionCookie: [] }],
    },
  },
  "/api/auth/convex/token": {
    get: {
      ...authRoute(
        "auth.convexToken",
        "A token for Convex",
        "A short-lived JWT for the signed-in session, to send to Convex functions as `Authorization: Bearer {token}`.",
        null,
        { type: "object", properties: { token: { type: "string" } } },
      ),
      security: [{ sessionCookie: [] }],
    },
  },
  "/api/auth/request-password-reset": {
    post: authRoute(
      "auth.requestPasswordReset",
      "Request a password reset",
      "Better Auth. Emails a reset link when the address has an account.",
      {
        type: "object",
        required: ["email"],
        properties: { email: { type: "string", format: "email" }, redirectTo: { type: "string" } },
      },
      { type: "object", properties: { status: { type: "boolean" } } },
    ),
  },
  "/api/auth/reset-password": {
    post: authRoute(
      "auth.resetPassword",
      "Set a new password",
      "Better Auth. Sets a new password with the token from the reset email.",
      {
        type: "object",
        required: ["newPassword", "token"],
        properties: { newPassword: { type: "string", minLength: 8 }, token: { type: "string" } },
      },
      { type: "object", properties: { status: { type: "boolean" } } },
    ),
  },
  "/api/company-summary": {
    post: {
      tags: ["website"],
      operationId: "companySummary.improve",
      summary: "Improve a company summary with AI",
      description:
        "Rewrites an SME's Professional company summary for procurement teams from its draft and profile, and lists important information that's missing. Never invents facts. Needs ANTHROPIC_API_KEY on the server.",
      servers: site,
      security: [{ sessionCookie: [] }],
      requestBody: {
        required: true,
        content: json({
          type: "object",
          required: ["draft", "profile"],
          properties: {
            draft: { type: "string", maxLength: 4000, description: "The SME's own words; may be empty" },
            profile: {
              type: "object",
              description: "The profile details the SME has entered",
              properties: {
                companyName: { type: "string" },
                industry: { type: "string" },
                yearsTrading: { type: "string" },
                employees: { type: "string" },
                city: { type: "string" },
                hqProvince: { type: "string" },
                services: { type: "array", items: { type: "string" } },
                capabilities: { type: "string" },
                accreditations: { type: "array", items: { type: "string" } },
                nationwide: { type: "boolean" },
                provinces: { type: "array", items: { type: "string" } },
                serviceAreas: { type: "array", items: { type: "string" } },
                bbbeeLevel: { type: "string" },
              },
            },
          },
        }),
      },
      responses: {
        200: {
          description: "The improved summary",
          content: json({
            type: "object",
            required: ["summary", "missingInformation"],
            properties: {
              summary: { type: "string" },
              missingInformation: { type: "array", items: { type: "string" }, maxItems: 4 },
            },
          }),
        },
        400: error,
        401: error,
        422: error,
        429: error,
        502: error,
        503: error,
      },
    },
  },
});

spec.tags.push({
  name: "website",
  description:
    "Routes on the MASLink website rather than Convex: signing in (Better Auth, which serves more routes than listed here, for organisations, teams and staff) and the AI company summary.",
});

spec.components.securitySchemes.sessionCookie = {
  type: "apiKey",
  in: "cookie",
  name: "better-auth.session_token",
  description: "The session cookie Better Auth sets on sign-in (prefixed __Secure- over HTTPS).",
};
spec.components.schemas.Session = {
  type: "object",
  nullable: true,
  properties: {
    user: {
      type: "object",
      properties: {
        id: { type: "string" },
        name: { type: "string" },
        email: { type: "string", format: "email" },
        role: { type: "string", description: "A MASLink staff role, for staff accounts" },
      },
    },
    session: {
      type: "object",
      properties: { id: { type: "string" }, expiresAt: { type: "string", format: "date-time" } },
    },
  },
};
spec.components.schemas.RouteError = { type: "object", properties: { error: { type: "string" } } };

/* ------------------------------------------------------------------------------------------------------ */
/* 4. Write it                                                                                            */
/* ------------------------------------------------------------------------------------------------------ */

mkdirSync(out, { recursive: true });
writeFileSync(
  path.join(out, "openapi.yaml"),
  `# Generated by pnpm docs:api. Don't edit by hand.\n${stringify(spec, { lineWidth: 0 })}`,
);
writeFileSync(
  path.join(out, "index.html"),
  `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>MASLink API</title>
    <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/swagger-ui/5.17.14/swagger-ui.min.css" />
    <style>body { margin: 0; background: #fff; }</style>
  </head>
  <body>
    <div id="swagger-ui"></div>
    <script src="https://cdnjs.cloudflare.com/ajax/libs/swagger-ui/5.17.14/swagger-ui-bundle.min.js"></script>
    <script>
      // Serve this folder (for example: pnpm dlx serve docs/api) and open it; browsers won't load the spec from file://
      window.ui = SwaggerUIBundle({ url: "openapi.yaml", dom_id: "#swagger-ui", deepLinking: true, docExpansion: "none" });
    </script>
  </body>
</html>
`,
);

const operations = Object.values(spec.paths).reduce((n, item) => n + Object.keys(item).length, 0);
console.log(
  `Wrote docs/api/openapi.yaml (${operations} operations in ${spec.tags.length} groups) and docs/api/index.html`,
);
